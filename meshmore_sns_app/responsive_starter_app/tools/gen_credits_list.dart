// Regenerates lib/legal/shipped_packages.dart.
//
// Run from the app directory:
//   flutter pub deps --no-dev | dart run tools/gen_credits_list.dart
//
// `--no-dev` is the whole point: it is the graph that ships. Flutter's licence
// registry carries the SDK's build-time packages and the dev graph too, which is
// right for licensing and wrong for a credits page.
import 'dart:io';

void main() {
  final List<String> shipped = <String>[];
  final List<int> bytes = <int>[];
  int b;
  while ((b = stdin.readByteSync()) != -1) {
    bytes.add(b);
  }
  final String input = String.fromCharCodes(bytes);
  for (final String line in input.split('\n')) {
    // Compact tree lines look like "├── archive 3.6.1" or "└── xml 6.5.0...".
    final RegExpMatch? m =
        RegExp(r'^[├└│─ ]*([a-z0-9_]+) [0-9]+\.[0-9]+\.[0-9]+').firstMatch(line);
    if (m != null) shipped.add(m.group(1)!);
  }
  shipped.sort();
  final String body = shipped.map((String n) => "  '$n',").join('\n');
  File('lib/legal/shipped_packages.dart').writeAsStringSync('''
// Copyright (c) 2026 IoTone, Inc.
// SPDX-License-Identifier: MIT
//
// Generated by tools/gen_credits_list.dart. Do not edit.
//
// The packages the app graph actually ships, from `flutter pub deps --no-dev`.

/// The Dart packages this build ships, alphabetically.
const List<String> kShippedPackages = <String>[
$body
];
''');
  stdout.writeln('${shipped.length} shipped packages written');
}
